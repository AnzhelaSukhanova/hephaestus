"""``compiler.json``: what a consumer needs to drive one installed compiler.

Per-version quirks are written here as facts, so consumers never parse
version strings: the wasm launcher is detected from the files present, the
inliner flag form from the version.
"""

from __future__ import annotations

from datetime import datetime, timezone
import json
import os
from pathlib import Path
import re
import tempfile
import zipfile

from .versions import BACKENDS, version_numbers


SCHEMA = 1
DESCRIPTOR = 'compiler.json'
ORIGINS = ('release', 'dev')
INLINER_FLAGS = ('mode', 'boolean')
WASM_VIA_JS_ARGS = ('-Xwasm', '-Xwasm-target=wasm-js')
# The directory parts each backend needs; parts are installed whole and never changed.
# ``stdlib`` is optional: it exists only when the zip lacks a JS/Wasm stdlib klib.
PARTS = {
    'jvm': ('kotlinc',),
    'js': ('kotlinc', 'stdlib'),
    'wasm': ('kotlinc', 'stdlib'),
    'native': ('native',),
}
PART_ORDER = ('kotlinc', 'stdlib', 'native')
OPTIONAL_PARTS = ('stdlib',)
STDLIB_KLIBS = {
    'kotlin-stdlib-js': 'kotlin-stdlib-js.klib',
    'kotlin-stdlib-wasm-js': 'kotlin-stdlib-wasm-js.klib',
    'kotlin-stdlib-wasm-wasi': 'kotlin-stdlib-wasm-wasi.klib',
}
NATIVE_STDLIB = 'native/klib/common/stdlib'
# First line after the shebang of the kotlinc-wasm front the manager writes when a zip has none.
SHIM_MARKER = '# kotlinc-wasm shim generated by src/tools/kotlin_compilers'


class DescriptorError(ValueError):
    pass


def parts_for(backends) -> list[str]:
    needed = {part for backend in backends for part in PARTS[backend]}
    return [part for part in PART_ORDER if part in needed]


def inliner_flag_style(version: str) -> str:
    """``boolean`` before 2.3.0 (on/off switch), ``mode`` from 2.3.0 on."""
    return 'boolean' if version_numbers(version) < (2, 3, 0) else 'mode'


def is_shim(path: Path) -> bool:
    try:
        with open(path, errors='replace') as script:
            return SHIM_MARKER in script.read(512)
    except OSError:
        return False


def stdlib_klib(directory: Path, name: str) -> str:
    """The zip's copy in ``kotlinc/lib`` when present, else the Maven copy in ``stdlib/``."""
    shipped = f'kotlinc/lib/{name}'
    return shipped if (directory / shipped).is_file() else f'stdlib/{name}'


def backend_entry(directory: Path, backend: str) -> dict:
    if backend == 'jvm':
        return {'launcher': 'kotlinc/bin/kotlinc-jvm', 'args': [],
                'stdlib': 'kotlinc/lib/kotlin-stdlib.jar'}
    if backend == 'js':
        return {'launcher': 'kotlinc/bin/kotlinc-js', 'args': [],
                'stdlib': stdlib_klib(directory, STDLIB_KLIBS['kotlin-stdlib-js'])}
    if backend == 'wasm':
        stdlib = stdlib_klib(directory, STDLIB_KLIBS['kotlin-stdlib-wasm-js'])
        launcher = directory / 'kotlinc/bin/kotlinc-wasm'
        if launcher.is_file():
            entry = {'launcher': 'kotlinc/bin/kotlinc-wasm', 'args': []}
            if is_shim(launcher):
                entry['shim'] = True
            return {**entry, 'stdlib': stdlib}
        # Installs from before the shim existed.
        return {'launcher': 'kotlinc/bin/kotlinc-js', 'args': list(WASM_VIA_JS_ARGS),
                'stdlib': stdlib}
    if backend == 'native':
        return {'launcher': 'native/bin/kotlinc-native', 'args': [], 'stdlib': NATIVE_STDLIB,
                'first_stage_only': True}
    raise DescriptorError(f'unknown backend {backend!r}')


def backends_on_disk(directory: Path) -> set[str]:
    """The backends whose launcher and stdlib are present in ``directory``."""
    found = set()
    for backend in BACKENDS:
        entry = backend_entry(directory, backend)
        if all((directory / entry[key]).exists() for key in ('launcher', 'stdlib')):
            found.add(backend)
    return found


def parse_manifest(text: str) -> dict[str, str]:
    values = {}
    for line in text.splitlines():
        key, separator, value = line.partition('=')
        if separator and not line.lstrip().startswith('#'):
            values[key.strip()] = value.strip()
    return values


def klib_manifest(path: Path) -> dict[str, str] | None:
    """The ``default/manifest`` of a packed or unpacked klib, if readable."""
    try:
        if path.is_dir():
            return parse_manifest((path / 'default/manifest').read_text())
        with zipfile.ZipFile(path) as archive:
            name = next(n for n in archive.namelist() if re.fullmatch(r'(?:\./)?default/manifest', n))
            return parse_manifest(archive.read(name).decode())
    except (OSError, StopIteration, zipfile.BadZipFile, KeyError):
        return None


def abi_version(directory: Path, version: str) -> str:
    """The ABI version from an installed stdlib manifest, else ``<maj>.<min>.0``."""
    candidates = [directory / NATIVE_STDLIB] + [directory / part / name
                                                for name in STDLIB_KLIBS.values()
                                                for part in ('kotlinc/lib', 'stdlib')]
    for candidate in candidates:
        if candidate.exists():
            manifest = klib_manifest(candidate)
            if manifest and manifest.get('abi_version'):
                return manifest['abi_version']
    major, minor, _ = version_numbers(version)
    return f'{major}.{minor}.0'


def build_descriptor(directory: Path, *, version: str, origin: str, host: str,
                     backends, installed_at: str | None = None) -> dict:
    selected = [backend for backend in BACKENDS if backend in backends]
    return {
        'schema': SCHEMA,
        'id': version,
        'version': version,
        'origin': origin,
        'host': host,
        'installed_at': installed_at or datetime.now(timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ'),
        'abi_version': abi_version(directory, version),
        'backends': {backend: backend_entry(directory, backend) for backend in selected},
        'inliner_flag': inliner_flag_style(version),
    }


def validate_descriptor(data: object, directory: Path) -> dict:
    if not isinstance(data, dict):
        raise DescriptorError(f'{directory / DESCRIPTOR}: expected a JSON object')
    if data.get('schema') != SCHEMA:
        raise DescriptorError(f'{directory / DESCRIPTOR}: unsupported schema {data.get("schema")!r}')
    for key in ('id', 'version', 'origin', 'host', 'abi_version', 'inliner_flag'):
        if not isinstance(data.get(key), str):
            raise DescriptorError(f'{directory / DESCRIPTOR}: missing {key!r}')
    if data['origin'] not in ORIGINS:
        raise DescriptorError(f'{directory / DESCRIPTOR}: unknown origin {data["origin"]!r}')
    if data['inliner_flag'] not in INLINER_FLAGS:
        raise DescriptorError(f'{directory / DESCRIPTOR}: unknown inliner_flag {data["inliner_flag"]!r}')
    backends = data.get('backends')
    if not isinstance(backends, dict):
        raise DescriptorError(f'{directory / DESCRIPTOR}: missing "backends"')
    for backend, entry in backends.items():
        if backend not in BACKENDS:
            raise DescriptorError(f'{directory / DESCRIPTOR}: unknown backend {backend!r}')
        if (not isinstance(entry, dict) or not isinstance(entry.get('launcher'), str)
                or not isinstance(entry.get('args'), list) or not isinstance(entry.get('stdlib'), str)):
            raise DescriptorError(f'{directory / DESCRIPTOR}: malformed {backend!r} entry')
        if not isinstance(entry.get('shim', False), bool):
            raise DescriptorError(f'{directory / DESCRIPTOR}: malformed {backend!r} shim flag')
        for key in ('launcher', 'stdlib'):
            if not (directory / entry[key]).exists():
                raise DescriptorError(f'{directory / DESCRIPTOR}: {backend} {key} '
                                      f'{entry[key]} is missing')
    return data


def read_descriptor(directory: Path) -> dict | None:
    """The validated descriptor, ``None`` if absent; :class:`DescriptorError` if corrupt."""
    path = directory / DESCRIPTOR
    try:
        text = path.read_text()
    except FileNotFoundError:
        return None
    except OSError as exc:
        raise DescriptorError(f'{path}: {exc}') from exc
    try:
        data = json.loads(text)
    except ValueError as exc:
        raise DescriptorError(f'{path}: invalid JSON: {exc}') from exc
    return validate_descriptor(data, directory)


def write_descriptor(directory: Path, data: dict) -> None:
    """Atomically replace ``compiler.json``."""
    validate_descriptor(data, directory)
    handle, temporary = tempfile.mkstemp(prefix='.compiler.', suffix='.json', dir=directory)
    try:
        with os.fdopen(handle, 'w') as output:
            json.dump(data, output, indent=2)
            output.write('\n')
        os.chmod(temporary, 0o644)
        os.replace(temporary, directory / DESCRIPTOR)
    except BaseException:
        Path(temporary).unlink(missing_ok=True)
        raise
