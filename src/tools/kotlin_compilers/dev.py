"""Dev builds (``master``) from the JetBrains dev Maven repo.

The repo has no ``kotlinc`` zip, so jvm/js/wasm are assembled from the plain
``kotlin-compiler`` jar plus its runtime dependencies (a deliberately minimal
POM resolver) and run through generated wrapper scripts, always including
``kotlinc-wasm``. Every jar and stdlib klib goes through the store, so the
recurring dependencies are linked instead of downloaded again. Native comes
from the ``kotlin-native-prebuilt`` tarball, trimmed and guarded as for
releases.
"""

from __future__ import annotations

from collections import deque
from dataclasses import dataclass
from pathlib import Path
import xml.etree.ElementTree as ElementTree
import zipfile

from . import download
from .descriptor import WASM_VIA_JS_ARGS
from .download import DownloadError
from .host import require_native_host
from .layout import Layout, Stager, install_version
from .releases import (
    MAVEN_CENTRAL, InstallError, artifact_url, kotlinc_libs, maven_url, stage_native_archive,
    stage_stdlib_klibs,
)
from .store import Store
from .versions import is_exact_version


DEV_REPO = 'https://packages.jetbrains.team/maven/p/kt/dev'
REPOSITORIES = (DEV_REPO, MAVEN_CENTRAL)
MASTER_ENV = 'KOTLIN_MASTER_VERSION'
KOTLIN = 'org.jetbrains.kotlin'
COMPILER = (KOTLIN, 'kotlin-compiler')
STDLIB = (KOTLIN, 'kotlin-stdlib')
FOLLOWED_SCOPES = (None, 'compile', 'runtime')
JVM_MAIN = 'org.jetbrains.kotlin.cli.jvm.K2JVMCompiler'
JS_MAIN = 'org.jetbrains.kotlin.cli.js.K2JSCompiler'
# Dedicated wasm entry points, newest first; without one wasm goes through kotlinc-js -Xwasm.
WASM_MAINS = (
    'org.jetbrains.kotlin.cli.js.KotlinWasmCompiler',
    'org.jetbrains.kotlin.cli.wasm.K2WasmCompiler',
    'org.jetbrains.kotlin.cli.js.K2WasmCompiler',
)
WRAPPER = '''#!/usr/bin/env bash
# Generated by src/tools/kotlin_compilers (dev build {version}); mirrors the release kotlinc launcher.
DIR="$(cd -P "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
LIB="$DIR/../lib"
KOTLIN_HOME="$(cd -P "$DIR/.." && pwd)"
[ -n "$JAVA_OPTS" ] || JAVA_OPTS="-Xmx512M -Xms128M"
if [ -z "$JAVACMD" ] && [ -n "$JAVA_HOME" ] && [ -x "$JAVA_HOME/bin/java" ]; then
    JAVACMD="$JAVA_HOME/bin/java"
fi
JAVACMD="${{JAVACMD:-java}}"
java_version="$("$JAVACMD" -version 2>&1 | sed -n 's/^.*version "\\([0-9]*\\).*$/\\1/p' | head -1)"
java_args=()
if [ "${{java_version:-0}}" -ge 24 ]; then
    java_args+=(--enable-native-access=ALL-UNNAMED --sun-misc-unsafe-memory-access=allow)
fi
kotlin_args=()
while [ $# -gt 0 ]; do
    case "$1" in
        -D*) java_args+=("$1") ;;
        -J*) java_args+=("${{1:2}}") ;;
        *) kotlin_args+=("$1") ;;
    esac
    shift
done
java_args+=("-Dkotlin.home=$KOTLIN_HOME")
exec "$JAVACMD" $JAVA_OPTS "${{java_args[@]}}" -cp "$LIB/*" {main} {args}"${{kotlin_args[@]}}"
'''


class DevError(ValueError):
    pass


@dataclass(frozen=True)
class Artifact:
    group: str
    name: str
    version: str
    repository: str
    packaging: str = 'jar'


def master_version(value: str | None) -> str | None:
    """The exact dev version named by ``KOTLIN_MASTER_VERSION``; ``None`` when unset."""
    value = (value or '').strip()
    if not value:
        return None
    if value == 'latest':
        raise DevError(f'{MASTER_ENV}=latest is unsupported: the dev repo also receives '
                       f'developer-branch builds with the same X.Y.Z-dev-N names, so it cannot '
                       f'name the newest master. Pass an exact version (e.g. 2.5.20-dev-1234) '
                       f'or leave it empty.')
    if not is_exact_version(value):
        raise DevError(f'{MASTER_ENV}={value!r} is not an exact Kotlin version '
                       f'(e.g. 2.5.20-dev-1234)')
    return value


def _children(element: ElementTree.Element, name: str) -> list[ElementTree.Element]:
    return [child for child in element if child.tag.rpartition('}')[2] == name]


def _text(element: ElementTree.Element, name: str) -> str | None:
    found = _children(element, name)
    return found[0].text.strip() if found and found[0].text else None


def parse_pom(text: str) -> tuple[str, list[dict]]:
    """``(packaging, dependencies)`` from a POM's top-level ``<dependencies>``."""
    root = ElementTree.fromstring(text)
    packaging = _text(root, 'packaging') or 'jar'
    dependencies = []
    for block in _children(root, 'dependencies'):
        for dependency in _children(block, 'dependency'):
            exclusions = {(_text(e, 'groupId') or '*', _text(e, 'artifactId') or '*')
                          for wrapper in _children(dependency, 'exclusions')
                          for e in _children(wrapper, 'exclusion')}
            dependencies.append({
                'group': _text(dependency, 'groupId'),
                'name': _text(dependency, 'artifactId'),
                'version': _text(dependency, 'version'),
                'scope': _text(dependency, 'scope'),
                'optional': _text(dependency, 'optional') == 'true',
                'type': _text(dependency, 'type') or 'jar',
                'exclusions': frozenset(exclusions),
            })
    return packaging, dependencies


def _excluded(group: str, name: str, exclusions) -> bool:
    return any(g in ('*', group) and a in ('*', name) for g, a in exclusions)


def fetch_pom(group: str, name: str, version: str,
              repositories=REPOSITORIES) -> tuple[str, str]:
    """The POM text and the first repository that has it."""
    for repository in repositories:
        text = download.read_text(artifact_url(repository, group, name, version, 'pom'))
        if text is not None:
            return text, repository
    raise DevError(f'{group}:{name}:{version} not found on '
                   f'{" or ".join(repositories)} (dev builds expire after about 10 days)')


def resolve_dependencies(group: str, name: str, version: str,
                         repositories=REPOSITORIES) -> list[Artifact]:
    """Runtime closure, nearest version wins; compile/runtime scopes and exclusions only."""
    resolved: dict[tuple[str, str], Artifact] = {}
    queue = deque([(group, name, version, frozenset())])
    seen = {(group, name)}
    while queue:
        group, name, version, exclusions = queue.popleft()
        text, repository = fetch_pom(group, name, version, repositories)
        try:
            packaging, dependencies = parse_pom(text)
        except ElementTree.ParseError as exc:
            raise DevError(f'{group}:{name}:{version}: unreadable POM: {exc}') from exc
        resolved[(group, name)] = Artifact(group, name, version, repository, packaging)
        for dependency in dependencies:
            key = (dependency['group'], dependency['name'])
            if (dependency['scope'] not in FOLLOWED_SCOPES or dependency['optional']
                    or dependency['type'] != 'jar' or key in seen
                    or _excluded(*key, exclusions)):
                continue
            child_version = dependency['version']
            if not child_version or '$' in child_version or child_version[0] in '[(':
                raise DevError(f'{group}:{name}:{version}: unsupported version '
                               f'{child_version!r} for {key[0]}:{key[1]}')
            seen.add(key)
            queue.append((*key, child_version, exclusions | dependency['exclusions']))
    return [artifact for artifact in resolved.values() if artifact.packaging != 'pom']


def wasm_main_class(compiler_jar: Path) -> str | None:
    wanted = {main.replace('.', '/') + '.class': main for main in WASM_MAINS}
    with zipfile.ZipFile(compiler_jar) as archive:
        found = {wanted[name] for name in archive.namelist() if name in wanted}
    return next((main for main in WASM_MAINS if main in found), None)


def write_wrapper(path: Path, version: str, main: str, args: tuple[str, ...] = ()) -> None:
    path.write_text(WRAPPER.format(version=version, main=main,
                                   args=''.join(f'{arg} ' for arg in args)))
    path.chmod(0o755)


def stage_dev_kotlinc(version: str, target: Path, final: Path, store: Store,
                      repositories=REPOSITORIES) -> None:
    artifacts = resolve_dependencies(*COMPILER, version, repositories)
    if STDLIB not in {(a.group, a.name) for a in artifacts}:
        _, repository = fetch_pom(*STDLIB, version, repositories)
        artifacts.append(Artifact(*STDLIB, version, repository))
    lib = target / 'lib'
    lib.mkdir(parents=True)
    for artifact in artifacts:
        url = artifact_url(artifact.repository, artifact.group, artifact.name, artifact.version)
        # Version-free names, as in a release zip: lib/kotlin-stdlib.jar sits next to the compiler.
        name = f'{artifact.name}.jar'
        store.fetch_or_link(url, lib / name, final / 'lib' / name)
    for required in ('kotlin-compiler.jar', 'kotlin-stdlib.jar'):
        # A store link only resolves once published, so it counts as present here.
        if not ((lib / required).is_file() or (lib / required).is_symlink()):
            raise InstallError(f'dev build {version}: {required} was not resolved')
    bin_dir = target / 'bin'
    bin_dir.mkdir()
    write_wrapper(bin_dir / 'kotlinc-jvm', version, JVM_MAIN)
    write_wrapper(bin_dir / 'kotlinc-js', version, JS_MAIN)
    wasm = wasm_main_class(lib / 'kotlin-compiler.jar')
    if wasm is not None:
        write_wrapper(bin_dir / 'kotlinc-wasm', version, wasm)
    else:
        write_wrapper(bin_dir / 'kotlinc-wasm', version, JS_MAIN, WASM_VIA_JS_ARGS)


def dev_native_candidates(version: str, host: str):
    return [(maven_url(DEV_REPO, 'kotlin-native-prebuilt', version, 'tar.gz', host),
             download.maven_checksum)]


def dev_stager(version: str, host: str, directory: Path, store: Store) -> Stager:
    def stage(part: str, target: Path, downloads: Path) -> None:
        final = directory / part
        if part == 'kotlinc':
            stage_dev_kotlinc(version, target, final, store)
        elif part == 'stdlib':
            stage_stdlib_klibs(DEV_REPO, version, target, final, store,
                               kotlinc_libs(target, final))
        elif part == 'native':
            stage_native_archive(dev_native_candidates(version, require_native_host(host)),
                                 target, downloads)
        else:
            raise InstallError(f'unknown part {part!r}')
    return stage


def install_dev(layout: Layout, version: str, backends, host: str) -> tuple[dict, list[str]]:
    if 'native' in backends:
        require_native_host(host)
    try:
        stage = dev_stager(version, host, layout.compiler_dir(version), Store(layout.store))
        return install_version(layout, version, origin='dev', host=host, backends=backends,
                               stage=stage)
    except DownloadError as exc:
        if isinstance(exc, download.NotFound):
            raise DevError(f'{exc} (not found on the dev repo; dev builds expire after '
                           f'about 10 days)') from exc
        raise
